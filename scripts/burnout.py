def msg(state: dict, key: str, **kw) -> str:
    t = tone_of(state)
    # L5 always softens back to supportive phrasing for lock/timer messages —
    # sarcasm has a floor.
    if key in ("lock", "timer_done") and kw.get("lvl", 0) >= 5:
        t = "supportive"
    return MSG[key][t].format(**kw)

def build_console_alerts(state: dict, block: dict, score: dict, cd: dict,
                         prompt: str = "", cwd: str | None = None) -> dict:
    """Returns hook-output JSON: a block decision, a systemMessage alert, or {}.

    Thresholds resolve through baseline → contract → sprint phase → deep-work
    project (cwd-aware). During preview mode (first 7 days from install) L4/L5
    surface as warnings instead of platform-blocking. Stuck-loop detection is
    conservative: console nudge only, never throttles or locks."""
    thresh = resolved_thresholds(state, cwd=cwd)

    # Deliberate-act passthrough: conversation, exit ritual, parking, emergencies.
    if cd["locked"] and prompt.strip().lower().startswith(PASS_PREFIXES):
        lvl = cd["lock_level"]
        return {"systemMessage": msg(state, "bg_open", lvl=lvl),
                "hookSpecificOutput": {"hookEventName": "UserPromptSubmit",
                    "additionalContext": f"Burnout Guard: L{lvl} lockout active; user "
                        "opened the bg: channel. Follow the lockout protocol — "
                        "conversation/status/parking/exit ritual yes, task work no. "
                        "Crisis or distress dissolves all lockout framing."}}
    # 0) Override grace window: enforcement pauses for 60 min after an L4 override.
    grace = state["last_alerts"].get("override_grace_until")
    if cd["locked"] and grace and now() < parse(grace):
        return {"systemMessage": "🧯 Override grace active — lockout enforcement "
                                 "resumes when the 60-minute window closes."}

    # 1) Locked.
    if cd["locked"]:
        lock_lvl = cd["lock_level"]
        if cd["timer_elapsed"]:
            reason = msg(state, "timer_done", lvl=lock_lvl, exitmax=EXIT_INDEX_MAX,
                         plan=(" plus a short written recovery plan" if lock_lvl >= 5 else ""))
        else:
            override_txt = (". One logged override is available for genuine emergencies"
                            if cd["override_available"] else
                            "; no override at this level" if lock_lvl >= 5 else
                            "; the override has been used")
            reason = msg(state, "lock", lvl=lock_lvl,
                         name="Hard Lockout" if lock_lvl >= 5 else "Lockout",
                         remaining=cd["remaining_human"], idx=cd["trigger_index"],
                         override=override_txt)
        # Preview mode: soften the platform block to a console warning so first-week
        # users see what would happen without being surprised. Real enforcement
        # engages once preview_until passes.
        if in_preview(state):
            return {"systemMessage": "🧯 PREVIEW: a real lockout would fire here. "
                    + reason
                    + " Real enforcement engages after "
                    + state.get("preview_until", "") + "."}
        return {"decision": "block", "reason": reason}

    msgs = []
    mins = block_minutes(block)

    # 2) Throttle reminder (rate-limited).
    if score["level"] == 3 and alert_due(state, "throttle", THROTTLE_REMINDER_MIN):
        msgs.append(msg(state, "throttle", index=score["index"]))

    # 3) Continuous-stretch alerts (personalised).
    long2 = thresh["long_block_2_min"]
    long1 = thresh["long_block_1_min"]
    if mins >= long2 and alert_due(state, "block150"):
        msgs.append(msg(state, "block150", h=int(mins // 60), m=int(mins % 60)))
    elif mins >= long1 and alert_due(state, "block90"):
        msgs.append(msg(state, "block90", mins=int(mins)))

    # 4) Heavy-day alert (personalised; contract can pull this earlier).
    today_min = sum(block_minutes(b) for b in state["blocks"]
                    if parse(b["start"]).date() == now().date())
    if today_min >= thresh["heavy_day_hours"] * 60 and alert_due(state, "heavyday", 120):
        msgs.append(msg(state, "heavyday", hours=f"{today_min / 60:.1f}"))

    # 5) Late-night start (contract can pull stop_by_hour earlier than 23).
    local_now = datetime.now()
    stop_h = thresh["stop_by_hour"]
    if (local_now.hour >= stop_h or local_now.hour < LATE_NIGHT_END) \
       and alert_due(state, "latenight", 120):
        msgs.append(msg(state, "latenight"))

    # 6) Stuck-loop nudge (conservative, console-only, never affects index/lockout).
    if state.get("config", {}).get("stuck_detection", True):
        stuck_threshold = thresh["long_block_1_min"] * STUCK_BLOCK1_FRACTION
        if mins >= stuck_threshold and alert_due(state, "stuck", STUCK_REPEAT_MIN):
            recent = recent_transcript_prompts(STUCK_WINDOW_MIN)
            if detect_stuck_loop(recent[-8:]):
                msgs.append("🧯 Looks like a stuck loop — several near-duplicate "
                            "prompts in the last few minutes. A fresh perspective "
                            "in 10 minutes will land more than another retry now.")

    # 7) Sprint-phase context line (rate-limited; just a quiet status reminder).
    sp = thresh["sprint_phase"]
    if sp == "recovery" and alert_due(state, "sprint_recovery", 240):
        msgs.append("🧯 Post-sprint recovery window — heavy-day threshold is tight; "
                    "this is the rest you committed to.")

    if msgs:
        return {"systemMessage": " ".join(msgs)}
    return {}

