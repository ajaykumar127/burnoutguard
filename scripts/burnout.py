def daily_focus_hours(blocks: list[dict], days: int) -> dict:
    """Return {date: focus_hours} over the trailing `days` days (UTC date keys)."""
    today = now().date()
    out = {today - timedelta(days=i): 0.0 for i in range(days)}
    for b in blocks:
        d = parse(b["start"]).date()
        if d in out:
            out[d] += block_minutes(b) / 60.0
    return out

def strain_score(state: dict) -> dict:
    """Whoop-flavoured strain: a 30-day rolling debt of (load above your typical
    daily) minus (recovery credit on light days). Distinct from the burnout index —
    index is now (am I burnt out?), strain is trajectory (am I heading there?). Both
    coexist in status/report; the SKILL.md tells Claude to surface them as different
    things so users don't average them in their head."""
    blocks = unified_blocks(state, days=STRAIN_LOOKBACK_DAYS)
    bl = baseline(state)
    # Use the user's heavy_day threshold as the "above your typical" reference. If
    # uncalibrated, use the absolute default.
    pivot_hours = bl["heavy_day_hours"]
    daily = daily_focus_hours(blocks, STRAIN_LOOKBACK_DAYS)
    debt_hours = 0.0
    for hours in daily.values():
        if hours > pivot_hours:
            debt_hours += (hours - pivot_hours)            # accumulate above-load
        elif hours == 0:
            debt_hours -= 0.5                              # full rest day = small credit
        elif hours < pivot_hours * 0.5:
            debt_hours -= 0.25                             # light day = tiny credit
    debt_hours = max(0.0, debt_hours)
    score = round(min(100.0, (debt_hours / MAX_STRAIN_DEBT_HRS) * 100.0), 1)
    band, instruction = STRAIN_DEBT_BANDS[-1][1], STRAIN_DEBT_BANDS[-1][2]
    for cap, label, advice in STRAIN_DEBT_BANDS:
        if score <= cap:
            band, instruction = label, advice
            break
    return {"score": score, "band": band, "debt_hours": round(debt_hours, 1),
            "pivot_hours": pivot_hours, "instruction": instruction,
            "lookback_days": STRAIN_LOOKBACK_DAYS}

# ---------------------------------------------------------------- sprint (v5)

def sprint_phase(state: dict) -> str:
    """One of: 'none', 'active', 'recovery', 'cancel_pending'."""
    sp = state.get("sprint")
    if not sp:
        return "none"
    n = now()
    if sp.get("pending_cancel") and parse(sp["pending_cancel"]["applies_at"]) > n:
        # Cancel queued — but during the cool-off the sprint stays active so the user
        # can finish what they committed to. Cancel takes effect after the cool-off.
        return "active" if parse(sp["until"]) > n else "recovery"
    if parse(sp["until"]) > n:
        return "active"
    if parse(sp.get("recovery_until", sp["until"])) > n:
        return "recovery"
    return "none"   # finished naturally; cleared on next save by settle_sprint

def settle_sprint(state: dict) -> bool:
    """Apply matured cancels and clear naturally-finished sprints. Returns True if
    state was mutated. Called from save paths."""
    sp = state.get("sprint")
    if not sp:
        return False
    n = now()
    pending = sp.get("pending_cancel")
    if pending and parse(pending["applies_at"]) <= n:
        audit(state, "sprint_cancel_applied", sp.get("name", ""))
        state["sprint"] = None
        return True
    if not pending and parse(sp.get("recovery_until", sp["until"])) <= n:
        audit(state, "sprint_finished", sp.get("name", ""))
        state["sprint"] = None
        return True
    return False

# ---------------------------------------------------------------- projects (v5)

def transcript_blocks_by_project(cutoff: datetime) -> dict[str, list[dict]]:
    """Group transcript-derived beats by cwd, then stitch into per-project blocks.
    Heartbeat-only blocks (no cwd) aren't bucketable here — they appear in totals
    but not in the per-project breakdown."""
    by_cwd: dict[str, list[datetime]] = {}
    if not TRANSCRIPTS_ROOT.exists() or not TRANSCRIPTS_ROOT.is_dir():
        return {}
    file_floor = (now() - timedelta(days=TRANSCRIPT_LOOKBACK_DAYS)).timestamp()
    files: list[Path] = []
    try:
        for proj in TRANSCRIPTS_ROOT.iterdir():
            if not proj.is_dir():
                continue
            try:
                for jsonl in proj.glob("*.jsonl"):
                    try:
                        if jsonl.stat().st_mtime >= file_floor:
                            files.append(jsonl)
                    except OSError:
                        continue
            except OSError:
                continue
    except OSError:
        return {}
    if len(files) > TRANSCRIPT_MAX_FILES:
        files.sort(key=lambda p: p.stat().st_mtime, reverse=True)
        files = files[:TRANSCRIPT_MAX_FILES]

    for jsonl in files:
        try:
            with jsonl.open("r", encoding="utf-8", errors="replace") as f:
                for line in f:
                    if '"type":"user"' not in line and '"type": "user"' not in line:
                        continue
                    try:
                        ev = json.loads(line)
                    except Exception:
                        continue
                    if ev.get("type") != "user":
                        continue
                    msg = ev.get("message") or {}
                    if not isinstance(msg.get("content"), str):
                        continue
                    dt = parse_iso_z(ev.get("timestamp", ""))
                    if dt is None or dt < cutoff:
                        continue
                    cwd = ev.get("cwd") or "(unknown)"
                    by_cwd.setdefault(cwd, []).append(dt)
        except (OSError, IOError):
            continue

    out: dict[str, list[dict]] = {}
    for cwd, beats in by_cwd.items():
        beats.sort()
        items = [(t, t, 1, is_late(t.astimezone())) for t in beats]
        out[cwd] = stitch_intervals(items)
    return out

def project_summary(state: dict, days: int = 7) -> list[dict]:
    """Top projects by trailing focus minutes, with deep-work flag. Best-effort."""
    cutoff = now() - timedelta(days=days)
    by_proj = transcript_blocks_by_project(cutoff)
    rows = []
    for cwd, blocks in by_proj.items():
        recent = [b for b in blocks if parse(b["end"]) >= cutoff]
        if not recent:
            continue
        total_min = sum(block_minutes(b) for b in recent)
        flag = (state.get("projects") or {}).get(cwd, {}).get("deep_work", False)
        rows.append({"path": cwd, "minutes_7d": round(total_min, 1),
                     "blocks_7d": len(recent),
                     "deep_work": flag,
                     "longest_block_min": round(max((block_minutes(b) for b in recent),
                                                   default=0), 1)})
    rows.sort(key=lambda r: r["minutes_7d"], reverse=True)
    return rows

def is_deep_work_cwd(state: dict, cwd: str | None) -> bool:
    if not cwd:
        return False
    p = (state.get("projects") or {}).get(cwd)
    return bool(p and p.get("deep_work"))

# ---------------------------------------------------------------- stuck loop (v5)

def _word_set(s: str) -> set[str]:
    return {w for w in (s.lower().split()) if len(w) >= 3}

def _jaccard(a: set, b: set) -> float:
    if not a and not b:
        return 1.0
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)

def detect_stuck_loop(prompts_recent: list[str]) -> bool:
    """Conservative spiral detector: pairwise mean Jaccard of word sets across the
    recent prompts. Designed to err toward false negatives — being wrong with a
    'looks like a loop' nudge is fine; being wrong with a lockout is not. Returns
    False below STUCK_MIN_PROMPTS so a single repeat never trips it."""
    if len(prompts_recent) < STUCK_MIN_PROMPTS:
        return False
    sets = [_word_set(p) for p in prompts_recent if p]
    if len(sets) < STUCK_MIN_PROMPTS:
        return False
    pairs = []
    for i in range(len(sets)):
        for j in range(i + 1, len(sets)):
            pairs.append(_jaccard(sets[i], sets[j]))
    if not pairs:
        return False
    return (sum(pairs) / len(pairs)) >= STUCK_JACCARD_MEAN

def recent_transcript_prompts(window_min: int) -> list[str]:
    """Best-effort: read the most recent transcript prompts within the time window.
    Returns [] on any error."""
    try:
        cutoff = now() - timedelta(minutes=window_min)
        prompts: list[tuple[datetime, str]] = []
        if not TRANSCRIPTS_ROOT.exists():
            return []
        # Only scan the few most recently modified jsonl files — recent prompts live
        # in the active session's jsonl, scanning all is overkill for a hint.
        all_files: list[Path] = []
        for proj in TRANSCRIPTS_ROOT.iterdir():
            if not proj.is_dir():
                continue
            for jsonl in proj.glob("*.jsonl"):
                try:
                    all_files.append(jsonl)
                except OSError:
                    continue
        all_files.sort(key=lambda p: p.stat().st_mtime, reverse=True)
        for jsonl in all_files[:6]:
            try:
                with jsonl.open("r", encoding="utf-8", errors="replace") as f:
                    for line in f:
                        if '"type":"user"' not in line:
                            continue
                        try:
                            ev = json.loads(line)
                        except Exception:
                            continue
                        if ev.get("type") != "user":
                            continue
                        msg = ev.get("message") or {}
                        c = msg.get("content")
                        if not isinstance(c, str):
                            continue
                        dt = parse_iso_z(ev.get("timestamp", ""))
                        if dt is None or dt < cutoff:
                            continue
                        prompts.append((dt, c))
            except (OSError, IOError):
                continue
        prompts.sort()
        return [p for _, p in prompts]
    except Exception:
        return []

# ---------------------------------------------------------------- recovery rx (v5)

def recovery_prescription(state: dict) -> dict:
    """Plain-language recovery suggestion, surfaced in cooldown_status and
    timer-elapsed messages. Derived from observable signal: last sleep score, late-
    night blocks last 7d, current strain. Intentionally simple — not medical."""
    bd_blocks = unified_blocks(state, days=7)
    late_n = sum(1 for b in bd_blocks if b.get("late_night"))
    last_sleep = None
    if state.get("checkins"):
        last_sleep = state["checkins"][-1].get("sleep")
    sl = strain_score(state)
    lines: list[str] = []
    if last_sleep is None or last_sleep < RECOVERY_GOOD_SLEEP:
        lines.append("a real night of sleep (8h target; phone out of room)")
    if late_n >= RECOVERY_LATE_NIGHT_OK:
        lines.append(f"a no-Claude window tomorrow until midday "
                     f"(you logged {late_n} late-night block{'s' if late_n != 1 else ''} "
                     "last 7 days)")
    if sl["score"] >= 60:
        lines.append("at least one fully off day in the next 72h before another sprint")
    if not lines:
        lines.append("light contact (status/checkin only) until the timer elapses, "
                     "then a fresh check-in — you may already be there")
    return {"strain": sl, "items": lines,
            "summary": "Recovery suggested: " + "; ".join(lines) + "."}

# ---------------------------------------------------------------- behaviour

def behaviour_score(state: dict) -> dict:
    """0-100 plus components, from merged blocks (+legacy sessions) over trailing 7 days.

    Sources merged: state['blocks'] (heartbeat-stitched, real-time) + Claude Code
    transcript prompts (cross-project, retroactive). Legacy `sessions` are still
    honoured as 30-min day credits. Records (longest-ever sprint, streak) are updated
    here so every score computation keeps them current."""
    cutoff = now() - timedelta(days=7)
    blocks = unified_blocks(state, days=7)
    sessions = [s for s in state["sessions"] if parse(s["ts"]) >= cutoff]
    update_records(state, unified_blocks(state, days=TRANSCRIPT_LOOKBACK_DAYS),
                   resolved_thresholds(state))

    daily_min: dict = {}
    for b in blocks:
        daily_min[parse(b["start"]).date()] = \
            daily_min.get(parse(b["start"]).date(), 0) + block_minutes(b)
    for s in sessions:                      # manual logs count as 30-min credits
        daily_min[parse(s["ts"]).date()] = daily_min.get(parse(s["ts"]).date(), 0) + 30

    avg_hours = (sum(daily_min.values()) / 60) / 7 if daily_min else 0
    longest = max((block_minutes(b) for b in blocks), default=0)
    late_n = sum(1 for b in blocks if b.get("late_night")) + \
             sum(1 for s in sessions if s.get("late_night"))

    days_active = set(daily_min)
    streak, d = 0, now().date()
    while d in days_active:
        streak += 1
        d -= timedelta(days=1)

    def clamp01(x): return max(0.0, min(1.0, x))
    volume = clamp01((avg_hours - 2) / 6) * 100          # 2h/day -> 0, 8h/day -> 100
    intensity = clamp01((longest - 60) / 180) * 100      # 1h block -> 0, 4h -> 100
    night = clamp01(late_n / 5) * 100                    # 5 late blocks/wk -> 100
    grind = clamp01((streak - 4) / 6) * 100              # 5-day streak counts, 10 max

    score = W_VOLUME * volume + W_NIGHT * night + W_STREAK * grind + W_INTENSITY * intensity
    return {"score": round(min(100, score), 1),
            "avg_hours_per_day": round(avg_hours, 2),
            "longest_block_min": round(longest),
            "late_night_blocks_7d": late_n,
            "streak_days": streak}

# ---------------------------------------------------------------- scoring

def clamp(v, lo, hi):
    return max(lo, min(hi, v))

def self_report_score(state: dict) -> float | None:
    """Prefer a fresh 5-item check-in (≤72h). If none, accept a fresh 1-item pulse
    (≤24h) at reduced weight via the index-only path. Returns None when neither
    source is fresh — behaviour-only mode (capped at L3) kicks in."""
    last_full = state["checkins"][-1] if state.get("checkins") else None
    if last_full and now() - parse(last_full["ts"]) <= timedelta(hours=72):
        raw = ((last_full["exhaustion"] - 1) * 1.25
               + (last_full["detachment"] - 1) * 1.25
               + (5 - last_full["efficacy"]) * 1.0
               + (5 - last_full["sleep"]) * 0.75
               + (last_full["pressure"] - 1) * 0.75)
        return clamp(raw * 5.0, 0, 100)

    last_pulse = state["pulses"][-1] if state.get("pulses") else None
    if last_pulse and now() - parse(last_pulse["ts"]) <= timedelta(hours=PULSE_FRESH_HOURS):
        return float(PULSE_TO_INDEX.get(int(last_pulse["value"]), 50))

    return None

def level_for(index: float) -> tuple[int, str]:
    for lvl, name, lo, hi in reversed(LEVELS):
        if index >= lo:
            return lvl, name
    return 0, "Flow"

def self_report_source(state: dict) -> str | None:
    """Which fresh source produced self_report_score, if any."""
    last_full = state["checkins"][-1] if state.get("checkins") else None
    if last_full and now() - parse(last_full["ts"]) <= timedelta(hours=72):
        return "checkin"
    last_pulse = state["pulses"][-1] if state.get("pulses") else None
    if last_pulse and now() - parse(last_pulse["ts"]) <= timedelta(hours=PULSE_FRESH_HOURS):
        return "pulse"
    return None

def compute_index(state: dict) -> dict:
    sr = self_report_score(state)
    bh = behaviour_score(state)
    src = self_report_source(state)
    if sr is None:
        index = clamp(bh["score"], 0, 64)   # behaviour alone can throttle, never lock
        basis = ("behaviour-only (no check-in/pulse fresh; capped at L3 — "
                 "log a pulse or check-in to lift the cap)")
    elif src == "pulse":
        # Pulse is a lighter self-report; weight it less than a full 5-item check-in.
        # Cap at L3 still lifts (we have *some* self-report), but blend leans behaviour.
        index = 0.4 * sr + 0.6 * bh["score"]
        index = max(index, sr * SEVERE_SELF_REPORT_FLOOR)
        basis = "blended (40% pulse, 60% behaviour; full check-in welcome)"
    else:
        index = SELF_REPORT_WEIGHT * sr + BEHAVIOUR_WEIGHT * bh["score"]
        index = max(index, sr * SEVERE_SELF_REPORT_FLOOR)
        basis = "blended (60% self-report, 40% behaviour; severe self-report floor)"
    index = clamp(index + state.get("override_penalty", 0), 0, 100)
    lvl, name = level_for(index)
    return {"index": round(index, 1), "level": lvl, "level_name": name,
            "self_report": None if sr is None else round(sr, 1),
            "self_report_source": src,
            "behaviour": bh["score"], "behaviour_detail": bh,
            "basis": basis, "override_penalty": state.get("override_penalty", 0)}

def cooldown_hours_for(index: float, level: int) -> int:
    if level >= 5:
        return int(round(36 + clamp((index - 85) / 15, 0, 1) * 36))
    return int(round(12 + clamp((index - 65) / 19, 0, 1) * 24))

# ---------------------------------------------------------------- cooldown

def start_cooldown(state: dict, index: float, level: int, reason: str) -> dict:
    hours = cooldown_hours_for(index, level)
    state["cooldown"] = {"started_at": iso(now()),
                         "ends_at": iso(now() + timedelta(hours=hours)),
                         "trigger_index": index, "trigger_level": level,
                         "reason": reason, "overrides": [], "recovery_plan": None}
    audit(state, "cooldown_start", f"L{level} index={index} hours={hours} reason={reason}")
    return state["cooldown"]

def maybe_escalate(state: dict, score: dict, source: str) -> None:
    lvl, idx = score["level"], score["index"]
    cd = state.get("cooldown")
    contract_floor = resolved_thresholds(state)["lockout_index"]   # 65 default; contract may lower
    contract_triggered = contract_floor < 65 and lvl < 4 and idx >= contract_floor
    if (lvl >= 4 or contract_triggered) and not cd:
        # Contract-triggered cooldowns label as L4 ("Lockout"): no task work, override available.
        effective_lvl = max(lvl, 4)
        reason = (f"contract: index {idx} >= committed floor {contract_floor}"
                  if contract_triggered else f"auto: L{lvl} on {source}")
        start_cooldown(state, idx, effective_lvl, reason)
    elif cd and lvl == 5 and cd.get("trigger_level", 4) < 5:
        start_cooldown(state, idx, 5, f"escalation: L4 -> L5 on {source}")

def cooldown_status(state: dict) -> dict:
    cd = state.get("cooldown")
    if not cd:
        return {"locked": False}
    remaining = parse(cd["ends_at"]) - now()
    timer_elapsed = remaining.total_seconds() <= 0
    lvl = cd.get("trigger_level", 4)
    return {"locked": True, "lock_level": lvl,
            "started_at": cd["started_at"], "ends_at": cd["ends_at"],
            "timer_elapsed": timer_elapsed,
            "remaining_human": "0h 0m" if timer_elapsed else
                f"{int(remaining.total_seconds() // 3600)}h {int(remaining.total_seconds() % 3600 // 60)}m",
            "trigger_index": cd["trigger_index"], "reason": cd["reason"],
            "override_available": lvl < 5 and len(cd.get("overrides", [])) == 0,
            "overrides_used": len(cd.get("overrides", [])),
            "exit_requires": f"timer elapsed AND fresh check-in (2h) with index <= {EXIT_INDEX_MAX}"
                             + (" AND a written recovery plan (--plan)" if lvl >= 5 else "")}

